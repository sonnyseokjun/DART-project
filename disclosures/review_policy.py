"""사람 검수 게이트 정책 — 어떤 공시를 **무조건** 사람이 보는가.

## 왜 AI의 중요도로 게이트를 걸면 안 되는가

4단계까지의 게이트는 `DisclosureSummary.importance == 'high'` 였다. 그런데 그 중요도는
**요약을 만든 그 AI가 매긴 값**이다. AI 요약을 못 믿어서 검수하는데 검수 대상 선정을
AI에게 맡기고 있었다. AI가 중요도를 낮게 잘못 매기면 그 요약은 검수 큐에 아예 안 뜬다 —
가장 위험한 실패가 조용히 통과하는 구조다.

그래서 게이트를 **DART가 부여한 공시 제목**이라는 객관적 사실로 옮긴다. 제목은 AI가
만들지 않았고 우리가 바꿀 수도 없으며, 같은 공시는 언제 처리해도 같은 판정을 받는다.

## 대상을 고른 기준 — '오류 가능성'이 아니라 '오류의 대가'

처음에는 "짧고 정형화된 공시는 AI가 틀릴 일이 적으니 빼자"는 기준을 세웠다.
**실데이터로 확인해 보니 틀렸다.** 원문 길이별 수치 경고 발생률은 이렇다.

    0~1,000자 11%  ·  1천~5천자 13%  ·  5천~2만자 16%  ·  2만~10만자 16%

길이와 오류율은 사실상 무관하다. 즉 **어느 유형이 더 잘 틀리는지는 데이터로 구분되지
않는다.** 그렇다면 게이트를 오류 가능성으로 정할 근거가 없다. 남는 축은 하나다.

> **요약이 틀렸을 때 독자가 치르는 대가가 되돌릴 수 없는가.**

이 기준으로 넣은 것과 뺀 것:

| 유형 | 판정 | 이유 |
|---|---|---|
| 유상증자·사채발행·증권신고서·DR | **포함** | 독자가 청약·매도를 실행한다. 실행하면 못 되돌린다 |
| 합병·분할·영업양수도·최대주주변경 | **포함** | 회사의 형태가 바뀐다. 판단 착오의 대가가 크다 |
| 상장폐지·부도·회생·감사의견 | **포함** | 원금 전액 손실이 걸린다 |
| 중대재해 | **포함** | 사람에 관한 사실이다. 틀리면 투자 손실과 종류가 다른 해를 끼친다 |
| 정기보고서·실적 공정공시 | 제외 | 정형 표에서 나온 수치이고, 틀려도 독자가 원문 표에서 즉시 확인·정정된다 |
| 공급계약·시설투자 | 제외 | 위험이 사실상 '금액 오류' 하나이고 그건 수치 검증기가 담당한다 |
| IR 개최·주주명부폐쇄·배당 | 제외 | 형식적 안내다 |

검수 게이트에서 빠진다고 검증을 안 받는 것이 아니다. 수치·인용 경고는 유형과 무관하게
전건에 걸리고, 경고가 붙으면 그 요약도 검수 큐에 들어온다(`DisclosureSummary.needs_review`).
이 게이트는 **경고가 하나도 없어도 사람이 봐야 하는 유형**을 지정하는 것이다.

## 판정 방식

`selection.normalize_title` 을 그대로 재사용한다(선행 `[기재정정]` 태그 제거 + 공백 제거).
정정 공시가 원 공시와 다른 판정을 받으면 안 되고, DART 제목에는 정렬용 연속 공백이 섞여
있기 때문이다. 실제로 `[기재정정]주요사항보고서(유상증자결정)` 이 이 정규화 덕분에
원 공시와 같은 판정을 받는다.

매칭은 **접두어**가 원칙이다(`^`). 부분 일치를 쓰면 `주요사항보고서(유상증자결정철회)`
같은 파생 서류까지 의도치 않게 걸리거나, 반대로 제목 뒷부분의 우연한 문자열에 걸린다.
접두어로 못 잡는 것만 예외로 부분 일치를 쓰고 그 자리에 이유를 적는다.
"""
import re

from django.db import models

from .selection import normalize_title


class ReviewCategory(models.TextChoices):
    """검수 필수 사유. 빈 문자열이면 게이트 비대상이다."""

    CAPITAL = 'capital', '자본구조 변동'
    CONTROL = 'control', '지배구조·존속 지위'
    DISTRESS = 'distress', '부실·감사의견'
    SAFETY = 'safety', '중대재해'


#: (사유, 제목 패턴) 목록. 위에서부터 먼저 걸리는 사유를 쓴다.
#:
#: 미래 대비로 넣어 둔 패턴이 있다(합병·분할·부도·회생·상장폐지·감사의견). 표본 140건에는
#: 0건이지만 **없다가 처음 나타나는 순간이 가장 위험한 순간**이라 미리 넣는다. 이 유형들은
#: 흔하지 않아서 나중에 "그런 공시가 오면 추가하자"고 미루면 실제로 올 때 없다.
REVIEW_REQUIRED_PATTERNS = (
    (ReviewCategory.CAPITAL, (
        re.compile(r'^주요사항보고서\(유상증자결정'),
        re.compile(r'^주요사항보고서\(무상증자결정'),
        re.compile(r'^주요사항보고서\(유무상증자결정'),
        re.compile(r'^주요사항보고서\(전환사채권발행결정'),
        re.compile(r'^주요사항보고서\(신주인수권부사채권발행결정'),
        re.compile(r'^주요사항보고서\(교환사채권발행결정'),
        # 증권신고서·투자설명서·발행실적보고서는 모집 조건 그 자체를 담은 서류다.
        re.compile(r'^증권신고서'),
        re.compile(r'^투자설명서'),
        re.compile(r'^증권발행실적보고서'),
        re.compile(r'^유상증자또는주식관련사채등의발행결과'),
        re.compile(r'^증권예탁증권\(DR\)발행결정'),
        re.compile(r'^전환청구권ㆍ신주인수권ㆍ교환청구권행사'),
    )),
    (ReviewCategory.CONTROL, (
        re.compile(r'^주요사항보고서\(회사합병결정'),
        re.compile(r'^주요사항보고서\(회사분할'),      # 분할결정·분할합병결정 공통
        re.compile(r'^주요사항보고서\(영업양수도결정'),
        re.compile(r'^주요사항보고서\(주식교환ㆍ이전결정'),
        re.compile(r'^주요사항보고서\(해외증권시장주권등상장'),  # 결정·완료 양쪽
        re.compile(r'^최대주주변경'),
        re.compile(r'^상장폐지'),
        re.compile(r'^관리종목'),
    )),
    (ReviewCategory.DISTRESS, (
        re.compile(r'^주요사항보고서\(부도발생'),
        re.compile(r'^주요사항보고서\(은행거래정지'),
        re.compile(r'^주요사항보고서\(회생절차'),
        re.compile(r'^주요사항보고서\(파산'),
        re.compile(r'^감사보고서'),
        # '감사의견'은 제목 중간에 온다(`회계감사인의감사의견(감사보고서)제출` 등).
        # 이 단어가 제목에 들어가면 의견 관련 공시로 보아도 오탐 위험이 낮다.
        re.compile(r'감사의견'),
    )),
    (ReviewCategory.SAFETY, (
        re.compile(r'^중대재해'),
    )),
)


def evaluate(report_name):
    """공시 제목 → 검수 필수 사유. 게이트 비대상이면 빈 문자열.

    모델에 의존하지 않는 순수 함수다(selection.evaluate 와 같은 형태).
    """
    normalized = normalize_title(report_name)
    for category, patterns in REVIEW_REQUIRED_PATTERNS:
        if any(pattern.search(normalized) for pattern in patterns):
            return category
    return ''


def evaluate_disclosure(disclosure):
    """Disclosure 인스턴스에 게이트 정책을 적용한다(저장은 호출자 몫)."""
    return evaluate(disclosure.report_name)


# ---------------------------------------------------------------------------
# 재생성 정책
# ---------------------------------------------------------------------------

#: 요약 1건당 허용하는 **재생성 횟수의 절대 상한**. 최초 생성은 포함하지 않는다.
#:
#: 상한이 이 파이프라인에서 유일한 비용 방어선이다. 재생성 판단이 검증 결과에 달려 있고
#: 검증이 계속 실패할 수 있으므로, 상한이 없으면 한 건이 무한히 LLM을 부른다.
#: 1로 둔 근거: 같은 프롬프트로 두 번 실패한 요약이 세 번째에 맞을 것이라는 근거가 없다.
#: 두 번째 실패는 프롬프트나 원문의 문제이므로 사람에게 넘기는 것이 싸다.
MAX_REGENERATION_ATTEMPTS = 1


def should_regenerate(blocking_warnings, attempts_so_far):
    """이 요약을 다시 생성해야 하는지. 비용이 나가는 판단이므로 조건을 좁게 잡는다.

    blocking_warnings: 게시를 막은 경고 목록(`verification.blocking_warnings` 의 반환).
    attempts_so_far:   이미 시도한 재생성 횟수(`DisclosureSummary.regeneration_count`).

    상한을 **호출자가 아니라 이 함수가** 판정한다. 호출부마다 상한을 다시 적으면
    한 곳만 빠뜨려도 비용이 새기 때문이다.
    """
    if not blocking_warnings:
        return False
    return attempts_so_far < MAX_REGENERATION_ATTEMPTS
